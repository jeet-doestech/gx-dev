/**
 * Deterministic conventional-commit message builder (PLAN §8 step 11).
 * Pure function: same input always yields the same message, no clock reads.
 */

export interface CommitMessageInput {
  request: string;
  runId: string;
  artifacts: string[];
  strategy: string;
}

const MAX_FIRST_LINE = 72;

/** Short branch-style run id: without the "run-" prefix, capped length. */
function shortRunId(runId: string): string {
  return runId.replace(/^run-/, "").slice(0, 12);
}

/**
 * Naive imperative summary: first line of the request, whitespace-collapsed,
 * trailing punctuation stripped, hard-trimmed (word boundary preferred) so
 * the full first line stays within 72 characters.
 */
function imperativeSummary(request: string, maxChars: number): string {
  const firstLine = request.split("\n", 1)[0] ?? request;
  const collapsed = firstLine.replace(/\s+/g, " ").trim();
  const stripped = collapsed.replace(/[.。!！?？:：;，,]+$/u, "");
  if (stripped.length <= maxChars) return stripped;
  if (maxChars <= 3) return stripped.slice(0, maxChars);
  const room = maxChars - 3;
  const cut = stripped.slice(0, room).trimEnd();
  const lastSpace = cut.lastIndexOf(" ");
  const trimmed = lastSpace > room * 0.6 ? cut.slice(0, lastSpace) : cut;
  return `${trimmed}...`;
}

export function buildCommitMessage(input: CommitMessageInput): string {
  const prefix = `gx-dev(${shortRunId(input.runId)}): `;
  const summary =
    imperativeSummary(input.request, MAX_FIRST_LINE - prefix.length) ||
    "apply gx-dev run result";
  const lines: string[] = [`${prefix}${summary}`, ""];

  lines.push(`Run-id: ${input.runId}`);
  lines.push(`Strategy: ${input.strategy}`);
  if (input.artifacts.length > 0) {
    lines.push("Artifacts:");
    for (const artifact of input.artifacts) {
      lines.push(`  - ${artifact}`);
    }
  }
  lines.push("");
  lines.push("Generated by gx-dev multi-agent workflow.");
  return lines.join("\n");
}
