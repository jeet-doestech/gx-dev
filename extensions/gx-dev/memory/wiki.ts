/**
 * Markdown page I/O with frontmatter for the gx-dev memory wiki (PLAN §10.2).
 *
 * Pages live under `<repo>/.gx-dev/memory/`. Fixed pages sit at the root
 * (`index.md`, `log.md`, `project-overview.md`, `architecture.md`,
 * `conventions.md`, `testing.md`); namespace directories (`decisions/`,
 * `features/`, `failures/`, `sources/`, `pins/`) are handled as page names
 * with slashes, e.g. page `decisions/2025-01-use-sqlite` maps to
 * `decisions/2025-01-use-sqlite.md`.
 */

/** Result of parsing a raw Markdown page. */
export interface ParsedPage {
  frontmatter: Record<string, string>;
  body: string;
}

/** Fixed wiki pages that exist at the memory root. */
export const PAGE_NAMES = [
  "index",
  "log",
  "project-overview",
  "architecture",
  "conventions",
  "testing",
] as const;

export type PageName = (typeof PAGE_NAMES)[number];

/** Namespace directories, addressed as page names with slashes. */
export const MEMORY_SUBDIRS = [
  "decisions",
  "features",
  "failures",
  "sources",
  "pins",
] as const;

/**
 * Frontmatter fields every hand-curated content page must define
 * (PLAN §10.5: provenance, scope, freshness, verification).
 * `index.md` and `log.md` are generated and not hand-validated.
 */
export const REQUIRED_FRONTMATTER = [
  "provenance",
  "scope",
  "freshness",
  "verification",
  "confidence",
  "updated",
] as const;

/** Pages that are generated by the store, never hand-validated. */
export function isGeneratedPage(name: string): boolean {
  return name === "index" || name === "log";
}

/** A page name is safe when it is a clean relative path without traversal. */
export function isValidPageName(name: string): boolean {
  if (name.length === 0) return false;
  if (name.includes("\\") || name.includes("..")) return false;
  if (name.startsWith("/") || name.endsWith("/")) return false;
  return !name.split("/").some((part) => part === "" || part === "." || part === "..");
}

/** Maps a page name to its file name (`decisions/x` -> `decisions/x.md`). */
export function pageFileName(page: string): string {
  const name = page.replace(/\.md$/i, "");
  if (!isValidPageName(name)) {
    throw new Error(`unsafe memory page name: ${page}`);
  }
  return `${name}.md`;
}

/**
 * Parses a raw page into frontmatter and body. When the page does not start
 * with a `---` frontmatter block (or the block holds no key lines), the whole
 * raw text is returned as the body with empty frontmatter.
 */
export function parsePage(raw: string): ParsedPage {
  const m = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(raw);
  if (m === null) return { frontmatter: {}, body: raw };
  const frontmatter: Record<string, string> = {};
  let keyCount = 0;
  for (const line of (m[1] ?? "").split(/\r?\n/)) {
    const idx = line.indexOf(":");
    if (idx <= 0) continue;
    const key = line.slice(0, idx).trim();
    if (!/^[A-Za-z0-9_-]+$/.test(key)) continue;
    frontmatter[key] = line.slice(idx + 1).trim();
    keyCount += 1;
  }
  // A `---` opener followed by prose (e.g. a leading horizontal rule) is not
  // frontmatter; treat the whole text as body.
  if (keyCount === 0 && (m[1] ?? "").trim() !== "") {
    return { frontmatter: {}, body: raw };
  }
  return { frontmatter, body: raw.slice(m[0].length) };
}

/** Serializes frontmatter and body back into raw page text (roundtrips). */
export function serializePage(frontmatter: Record<string, string>, body: string): string {
  const entries = Object.entries(frontmatter).map(([key, value]) => `${key}: ${value}`);
  const head = entries.length > 0 ? `---\n${entries.join("\n")}\n---\n` : "---\n---\n";
  return `${head}${body}`;
}

/** Extracts `[[wiki link]]` targets (strips `|alias` and a `.md` suffix). */
export function extractLinks(raw: string): string[] {
  const targets: string[] = [];
  const re = /\[\[([^\[\]]+)\]\]/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(raw)) !== null) {
    const target = ((m[1] ?? "").split("|")[0] ?? "").trim().replace(/\.md$/i, "");
    if (target !== "") targets.push(target);
  }
  return targets;
}
